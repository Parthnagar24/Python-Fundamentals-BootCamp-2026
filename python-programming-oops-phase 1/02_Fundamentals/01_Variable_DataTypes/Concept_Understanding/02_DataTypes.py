a = 1           # a is an integer

b = 5.22        # b is a floating point number

c = "Hello"     # c is a string

d = False       # d is a boolean value

e = None         # e is a NoneType variable   

print(a, type(a))
print(b, type(b))
print(c, type(c))
print(d, type(d))
print(e, type(e))

# type() function is used to check the data type of a variable. 
  